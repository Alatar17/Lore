export function createDefaultTierRows(): TierRow[] {
  const names = ['S', 'A', 'B', 'C', 'D', 'F'];
  return names.map((name, i) => ({
    id: `row_${name.toLowerCase()}_${Date.now()}_${i}`,
    name,
    color: DEFAULT_TIER_COLORS[i % DEFAULT_TIER_COLORS.length],
  }));
}

